// Blueprint sketches of the ships, in metres. 35 ships have outlines traced from the wiki's
// blueprint sheets (outlines.json, built by backend/tools/ship_outlines.py, with a rear view), and
// more can be traced from the game's schematics (no rear view); the others are hand-drawn for ED Explorer Kit (fan art, not Frontier's art). Dimensions and
// makers: Elite Dangerous Wiki (2026-10-21; the Alliance Challenger, missing there, takes the
// Chieftain's hull). The shapes are described in ShipSketch.tsx.

import outlines from './outlines.json'

type Pt = [number, number]

export interface ShipSketch {
  maker: string
  /** Length, width, height. */
  dims: [number, number, number]
  top: Pt[]
  topPanels?: Pt[][]
  topShapes?: Pt[][]
  engines?: Pt[]
  side: Pt[]
  sidePanels?: Pt[][]
  sideShapes?: Pt[][]
  sideEngine?: [number, number]
  /** Traced sheets only: the rear view's half outline [y, z], y >= 0, z from the top down. */
  rear?: Pt[]
  /** Where traced outlines come from: a blueprint sheet or the game's schematic. */
  traced?: 'sheet' | 'game'
}

/** A traced sheet: fractions of the length, width and height (see ship_outlines.py). */
interface Outline {
  source: string
  top: number[][]
  topLines: number[][][]
  side: number[][]
  sideLines: number[][][]
  rear?: number[][]
}

function traced(hand: ShipSketch, o: Outline): ShipSketch {
  const [L, W, H] = hand.dims
  const at = (kx: number, ky: number) => (p: number[]): Pt => [p[0] * kx, p[1] * ky]
  return {
    maker: hand.maker,
    dims: hand.dims,
    top: o.top.map(at(L, W)),
    topPanels: o.topLines.map((l) => l.map(at(L, W))),
    side: o.side.map(at(L, H)),
    sidePanels: o.sideLines.map((l) => l.map(at(L, H))),
    rear: o.rear?.map(at(W, H)),
    traced: o.source === 'game' ? 'game' : 'sheet',
  }
}

